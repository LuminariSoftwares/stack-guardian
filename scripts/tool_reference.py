"""Render the README's MCP tool reference from the live tool schemas, so the two cannot drift.

    python scripts/tool_reference.py           # print the reference
    python scripts/tool_reference.py --write   # rewrite it in README.md between the markers
    python scripts/tool_reference.py --check   # exit 1 if README.md is out of date (CI and tests run this)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from stack_guardian.mcp_server import TOOL_SPECS  # noqa: E402

START = "<!-- tool-reference:start (generated by scripts/tool_reference.py; do not edit by hand) -->"
END = "<!-- tool-reference:end -->"
HINTS = ("readOnlyHint", "destructiveHint", "idempotentHint", "openWorldHint")


def _constraints(spec):
    parts = []
    for key in ("minLength", "maxLength", "pattern"):
        if key in spec:
            parts.append("%s `%s`" % (key, spec[key]))
    return ", ".join(parts) or "-"


def render(specs=TOOL_SPECS):
    out = [START, ""]
    for tool in specs:
        ann = tool["annotations"]
        out.append("#### `%s` - %s" % (tool["name"], tool["title"]))
        out.append("")
        out.append(tool["description"])
        out.append("")
        out.append("Annotations: " + ", ".join("`%s: %s`" % (h, str(ann[h]).lower()) for h in HINTS))
        out.append("")
        schema = tool["inputSchema"]
        required = set(schema.get("required", []))
        out.append("| parameter | type | required | default | constraints | example |")
        out.append("|---|---|---|---|---|---|")
        for name, spec in schema["properties"].items():
            default = "-" if name in required else "`%s`" % (spec["default"],)
            out.append("| `%s` | %s | %s | %s | %s | `%s` |" % (
                name, spec["type"], "yes" if name in required else "no", default.replace("``", '`""`'),
                _constraints(spec), spec["examples"][0]))
        out.append("")
    out.append(END)
    return "\n".join(out)


def splice(readme, block):
    head, sep, rest = readme.partition(START)
    if not sep or END not in rest:
        raise SystemExit("README.md has no tool-reference markers")
    return head + block + rest.split(END, 1)[1]


def main(argv):
    if "--write" not in argv and "--check" not in argv:
        print(render())
        return 0
    path = ROOT / "README.md"
    readme = path.read_text(encoding="utf-8")
    wanted = splice(readme, render())
    if "--write" in argv:
        path.write_text(wanted, encoding="utf-8", newline="\n")
        return 0
    if "--check" in argv:
        if wanted != readme:
            print("README.md tool reference is stale: run python scripts/tool_reference.py --write", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
